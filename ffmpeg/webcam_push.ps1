function Get-CapturePreset {
    $preset = "1080p"
    if (Test-Path $resFile) {
        $val = (Get-Content $resFile -Raw -ErrorAction SilentlyContinue)
        if ($val) { $val = $val.Trim() }
        if ($val -in @("480p", "720p", "1080p")) { $preset = $val }
    }
    switch ($preset) {
        "480p"  { return @{ Input = @("-video_size", "640x480", "-framerate", "30", "-pixel_format", "yuyv422"); G = "30"; Bitrate = "2M" } }
        "720p"  { return @{ Input = @("-video_size", "1280x720", "-framerate", "10", "-pixel_format", "yuyv422"); G = "10"; Bitrate = "7M" } }
        "1080p" { return @{ Input = @("-video_size", "1920x1080", "-framerate", "30", "-vcodec", "mjpeg"); G = "30"; Bitrate = "8M" } }
    }
}

