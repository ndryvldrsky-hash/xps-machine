    if (-not $localIp) { $localIp = "no-ip" }
    $tsIp = (Get-NetIPAddress -InterfaceAlias "Tailscale" -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.IPAddress -notlike "169.254.*" } | Select-Object -First 1).IPAddress
    if (-not $tsIp) { $tsIp = "no-ts" }
    $resLabel = "$($inputArgs[1])@$($inputArgs[3])fps $($preset.Bitrate)"
    # 2026-09-04: правый верхний угол — только адреса (LAN/TS), параметры потока
    # (разрешение/fps/битрейт) переехали в правый нижний угол на место бывшего FPS,
    # см. $streamInfoOverlay и комментарий про -t 300 в начале файла.
    $infoOverlay = "drawtext=${fontOpt}:text='LAN\: $localIp':x=w-tw-10:y=10,drawtext=${fontOpt}:text='TS\: $tsIp':x=w-tw-10:y=36"
    $streamInfoOverlay = "drawtext=${fontOpt}:text='$resLabel':x=w-tw-10:y=h-th-10"

    $procAmpVals = [XpsCam.ProcAmp]::GetValues()
    $procAmpLines = @()
    for ($i = 0; $i -lt $procAmpLabels.Count; $i++) {
        $rowFromBottom = ($procAmpLabels.Count - 1) - $i
        $yExpr = if ($rowFromBottom -eq 0) { "h-th-10" } else { "h-th-10-$($rowFromBottom * 26)" }
        $procAmpLines += "drawtext=${fontOpt}:text='$($procAmpLabels[$i])\: $($procAmpVals[$i])':x=10:y=$yExpr"
    }
    $procAmpOverlay = $procAmpLines -join ","

    & $ffmpeg -hide_banner -y -f dshow $inputArgs `
        -rtbufsize 100M -i video="Integrated Webcam" `
        -vf "$timeOverlay,$infoOverlay,$streamInfoOverlay,$procAmpOverlay,format=nv12" -c:v h264_mf -hw_encoding 1 -scenario live_streaming -g $preset.G -fps_mode cfr -b:v $preset.Bitrate -t 300 `
        -f flv rtmp://127.0.0.1:1935/xps 2>> $log
    Start-Sleep -Seconds 3
}
